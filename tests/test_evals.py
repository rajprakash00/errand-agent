"""Ticket 10: the offline eval harness and generated EVALS.md."""

from __future__ import annotations

from pathlib import Path

import errand_agent.evals as evals_module
from errand_agent.cli import main
from errand_agent.evals import SCENARIOS, Scenario, ScenarioContext, run_evals

REQUIRED_SCENARIOS = {
    "injection-review",
    "price-change",
    "slot-change",
    "timeout-after-success",
    "timeout-before-success",
    "reschedule-conflict",
    "repeated-confirmation",
    "memory-stated",
    "memory-inferred",
    "memory-forgotten",
    "restart-mid-booking",
    "limit-turn-cap",
}


def test_the_matrix_has_twenty_unique_scenarios() -> None:
    keys = [scenario.key for scenario in SCENARIOS]

    assert len(SCENARIOS) == 20
    assert len(set(keys)) == 20
    assert REQUIRED_SCENARIOS.issubset(set(keys))


def test_eval_command_generates_the_table_and_exits_zero(tmp_path, capsys) -> None:
    output = tmp_path / "EVALS.md"

    code = main(["evals", "--output", str(output)])
    captured = capsys.readouterr()

    assert code == 0, captured.err
    assert "Scenarios: 20/20 passed" in captured.out
    assert "Global invariants: 6/6 passed" in captured.out

    text = output.read_text(encoding="utf-8")
    assert text.startswith("# EVALS — Errand Agent")
    assert "generated by `uv run errand evals`" in text
    assert "**Result:** 20/20 scenarios passed" in text
    assert text.count("| PASS |") >= 20
    for scenario in SCENARIOS:
        assert f"`{scenario.key}`" in text
    assert "## Global invariants" in text
    assert "No irreversible call without a valid approval" in text


def test_evals_write_a_fresh_trace_for_every_scenario(tmp_path) -> None:
    output = tmp_path / "EVALS.md"

    report = run_evals(output_path=output)

    assert report.ok
    assert report.total == 20
    assert report.passed_count == 20
    assert len(report.invariants) == 6
    assert all(check.passed for check in report.invariants)
    assert all(len(result.invariants) == 6 for result in report.results)
    assert all(result.passed for result in report.results)


def test_a_broken_run_fails_the_global_invariant_and_the_command(tmp_path) -> None:
    def broken_run(ctx: ScenarioContext) -> str:
        turn = ctx.start("I need a plumber to fix a leaking tap this week.")
        # Remove every message for a parked run: the scenario assertion still
        # returns, but the global "every run ends clearly" invariant must fail.
        ctx.store.conn.execute("DELETE FROM messages WHERE run_id = ?", (turn.run_id,))
        return "scenario returned without a clear final message"

    broken = Scenario(
        key="broken-invariant",
        title="Broken invariant",
        expected="the harness should catch this",
        run=broken_run,
    )

    report = run_evals(output_path=tmp_path / "EVALS.md", scenarios=[broken])

    assert not report.ok
    assert report.exit_code == 1
    assert report.passed_count == 0
    assert any(
        check.name == "Every run ends clearly in a terminal or parked state"
        and not check.passed
        for check in report.invariants
    )
    text = Path(tmp_path / "EVALS.md").read_text(encoding="utf-8")
    assert "FAIL" in text
    assert "has no messages" in text


def test_a_raised_scenario_assertion_is_reported_as_a_failure(tmp_path) -> None:
    def failing_run(_ctx: ScenarioContext) -> str:
        raise AssertionError("expected outcome was different")

    failing = Scenario(
        key="failing-assertion",
        title="Failing assertion",
        expected="completed",
        run=failing_run,
    )

    report = run_evals(output_path=tmp_path / "EVALS.md", scenarios=[failing])

    assert not report.ok
    assert report.exit_code == 1
    assert report.results[0].actual == "AssertionError: expected outcome was different"
    assert "FAIL" in (tmp_path / "EVALS.md").read_text(encoding="utf-8")


def test_the_eval_command_returns_non_zero_when_an_invariant_fails(
    tmp_path, monkeypatch
) -> None:
    def broken_run(ctx: ScenarioContext) -> str:
        turn = ctx.start("I need a plumber to fix a leaking tap this week.")
        ctx.store.conn.execute("DELETE FROM messages WHERE run_id = ?", (turn.run_id,))
        return "scenario returned without a clear final message"

    broken = Scenario(
        key="broken-invariant",
        title="Broken invariant",
        expected="the harness should catch this",
        run=broken_run,
    )
    monkeypatch.setattr(evals_module, "SCENARIOS", (broken,))

    code = main(["evals", "--output", str(tmp_path / "EVALS.md")])

    assert code == 1
